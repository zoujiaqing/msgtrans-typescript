// Generate api-report.txt — the committed snapshot of the PUBLIC surface.
//
// Includes only the .d.ts files REACHABLE from the package's export entries
// (BFS over relative import/export specifiers). Concatenating all of dist/
// would freeze internal modules (request-manager, inbound-normalizer, …)
// that the package does not export — the opposite of a public API gate.
//
// Usage: npm run build && node scripts/gen-api-report.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'dist');

const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const entries = Object.values(pkg.exports ?? {})
  .map((e) => (typeof e === 'string' ? e : e.types))
  .filter(Boolean)
  .map((p) => p.replace(/^\.\/dist\//, ''));

const seen = new Set();
const queue = [...entries];
while (queue.length) {
  const file = queue.shift();
  if (seen.has(file)) continue;
  const path = join(dist, file);
  if (!existsSync(path)) {
    console.error(`entry not built: ${file} — run \`npm run build\` first`);
    process.exit(1);
  }
  seen.add(file);
  const src = readFileSync(path, 'utf8');
  for (const m of src.matchAll(/from '(\.[^']+)\.js'/g)) {
    queue.push(
      join(dirname(file), `${m[1]}.d.ts`).replaceAll('\\', '/'),
    );
  }
}

const files = [...seen].sort();
let out =
  '// Public API snapshot — generated by scripts/gen-api-report.mjs.\n' +
  '// Only modules REACHABLE from the package exports are included.\n' +
  '// Regenerate (npm run build && npm run api-report) and commit together\n' +
  '// with any intentional surface change; CI fails on drift.\n\n';
for (const f of files) {
  out += `// ===== ${f} =====\n`;
  out += readFileSync(join(dist, f), 'utf8');
  out += '\n';
}
writeFileSync(join(root, 'api-report.txt'), out);
console.log(`api-report.txt written (${files.length} reachable modules)`);
