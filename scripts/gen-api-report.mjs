// Generate api-report.txt — the committed snapshot of the public surface.
//
// Concatenates every dist/*.d.ts in stable order. CI regenerates it and
// fails on any diff, so an unreviewed change to the public API cannot land
// silently (the TS twin of the Rust repo's public-api.txt gate).
//
// Usage: npm run build && node scripts/gen-api-report.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'dist');

const files = readdirSync(dist)
  .filter((f) => f.endsWith('.d.ts'))
  .sort();

if (files.length === 0) {
  console.error('no .d.ts files in dist/ — run `npm run build` first');
  process.exit(1);
}

let out =
  '// Public API snapshot — generated by scripts/gen-api-report.mjs.\n' +
  '// Regenerate (npm run build && npm run api-report) and commit together\n' +
  '// with any intentional surface change; CI fails on drift.\n\n';
for (const f of files) {
  out += `// ===== ${f} =====\n`;
  out += readFileSync(join(dist, f), 'utf8');
  out += '\n';
}

writeFileSync(join(root, 'api-report.txt'), out);
console.log(`api-report.txt written (${files.length} files)`);
